-- Multiplayer schema for the IPL Auction Arena.
create extension if not exists pgcrypto;

create table if not exists public.players (
  id bigint primary key,
  name text not null,
  role text not null,
  country text not null,
  base_price integer not null,
  sort_order integer not null unique
);
create table if not exists public.rooms (
  code text primary key check (length(code)=5),
  host_member_id text not null,
  host_name text not null,
  host_team text not null,
  status text not null default 'auction' check (status in ('auction','simulation','complete')),
  current_index integer not null default 0,
  current_bid integer not null default 0,
  current_bidder text,
  timer_seconds integer not null default 20 check (timer_seconds in (5,10,15,20)),
  paused boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.room_members (
  room_code text not null references public.rooms(code) on delete cascade,
  member_id text not null,
  name text not null,
  team text not null,
  joined_at timestamptz not null default now(),
  primary key (room_code,team),
  unique (room_code,member_id)
);
create table if not exists public.sold_players (
  id bigint generated by default as identity primary key,
  room_code text not null references public.rooms(code) on delete cascade,
  player_index integer not null,
  player_name text not null,
  team text not null,
  price integer not null,
  sold_at timestamptz not null default now(),
  unique (room_code,player_index)
);
create table if not exists public.room_messages (
  id uuid primary key default gen_random_uuid(),
  room_code text not null references public.rooms(code) on delete cascade,
  team text not null,
  sender_name text not null,
  message text not null check (length(message) between 1 and 160),
  created_at timestamptz not null default now()
);

alter table public.players enable row level security;
