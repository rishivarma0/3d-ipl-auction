create policy "public read members" on public.room_members for select using (true);
drop policy if exists "public read sold" on public.sold_players;
create policy "public read sold" on public.sold_players for select using (true);
drop policy if exists "public read messages" on public.room_messages;
create policy "public read messages" on public.room_messages for select using (true);
drop policy if exists "public write messages" on public.room_messages;
create policy "public write messages" on public.room_messages for insert with check (true);

create or replace function public.create_room(p_code text,p_member_id text,p_name text,p_team text,p_timer_seconds integer default 20)
returns text language plpgsql security definer set search_path=public as $$
begin
 insert into rooms(code,host_member_id,host_name,host_team,timer_seconds) values(upper(p_code),p_member_id,p_name,p_team,p_timer_seconds);
 insert into room_members(room_code,member_id,name,team) values(upper(p_code),p_member_id,p_name,p_team);
 return upper(p_code);
end; $$;

create or replace function public.join_room(p_code text,p_member_id text,p_name text,p_team text)
returns text language plpgsql security definer set search_path=public as $$
begin
 if not exists(select 1 from rooms where code=upper(p_code)) then raise exception 'Room not found'; end if;
 insert into room_members(room_code,member_id,name,team) values(upper(p_code),p_member_id,p_name,p_team);
 return upper(p_code);
exception when unique_violation then raise exception 'That franchise or player is already in this room';
end; $$;

create or replace function public.place_bid(p_code text,p_team text,p_member_id text,p_amount integer)
returns void language plpgsql security definer set search_path=public as $$
declare r rooms%rowtype; p players%rowtype; next_bid integer; spent integer;
begin
 select * into r from rooms where code=upper(p_code) for update;
 if r is null or r.status<>'auction' or r.paused then raise exception 'Auction is not live'; end if;
 if not exists(select 1 from room_members where room_code=r.code and member_id=p_member_id and team=p_team) then raise exception 'You are not registered for this franchise'; end if;
 select * into p from players where sort_order=r.current_index;
 next_bid:=case when r.current_bid=0 then p.base_price when r.current_bid<100 then r.current_bid+5 when r.current_bid<200 then r.current_bid+10 else r.current_bid+25 end;
 if p_amount<>next_bid then raise exception 'Bid is out of sequence'; end if;
 if r.current_bidder=p_team then raise exception 'Your franchise already leads'; end if;
 select coalesce(sum(price),0) into spent from sold_players where room_code=r.code and team=p_team;
 if spent+p_amount>12000 then raise exception 'This franchise has reached its 120 Cr purse limit'; end if;
 update rooms set current_bid=p_amount,current_bidder=p_team where code=r.code;
end; $$;

create or replace function public.resolve_lot(p_code text,p_member_id text)
returns void language plpgsql security definer set search_path=public as $$
declare r rooms%rowtype; p players%rowtype;
begin
 select * into r from rooms where code=upper(p_code) for update;
 if r.host_member_id<>p_member_id then raise exception 'Only the host can resolve a lot'; end if;
 if r.status<>'auction' or r.paused then raise exception 'Auction is paused or complete'; end if;
 select * into p from players where sort_order=r.current_index;
 if r.current_bidder is not null then
  insert into sold_players(room_code,player_index,player_name,team,price) values(r.code,r.current_index,p.name,r.current_bidder,r.current_bid);
 end if;
 if r.current_index>=(select max(sort_order) from players) then
  update rooms set status='complete',current_bid=0,current_bidder=null where code=r.code;
 else
  update rooms set current_index=current_index+1,current_bid=0,current_bidder=null where code=r.code;
 end if;
end; $$;

create or replace function public.update_room_controls(p_code text,p_member_id text,p_timer_seconds integer,p_paused boolean)
returns void language plpgsql security definer set search_path=public as $$
begin
 if not exists(select 1 from rooms where code=upper(p_code) and host_member_id=p_member_id) then raise exception 'Only the host can change room controls'; end if;
 update rooms set timer_seconds=p_timer_seconds,paused=p_paused where code=upper(p_code);
end; $$;

create or replace function public.end_auction_early(p_code text,p_member_id text)
returns void language plpgsql security definer set search_path=public as $$
declare r rooms%rowtype; insufficient text;
begin
 select * into r from rooms where code=upper(p_code);
 if r.host_member_id<>p_member_id then raise exception 'Only the host can end the auction'; end if;
 select string_agg(team,', ') into insufficient from room_members m where m.room_code=r.code and (select count(*) from sold_players s where s.room_code=r.code and s.team=m.team)<15;
 if insufficient is not null then raise exception 'Every franchise needs at least 15 players before simulation. Still short: %',insufficient; end if;
 update rooms set status='simulation',paused=true where code=r.code;
end; $$;

